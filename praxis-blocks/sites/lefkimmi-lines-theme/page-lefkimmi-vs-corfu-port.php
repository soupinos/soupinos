        <h2 style="font-family:var(--fontH);color:var(--navy);font-size:26px;margin:0 0 14px;">Two ports, two very different experiences</h2>
        <p>If you're travelling to Corfu from Igoumenitsa on the Greek mainland, you have two ferry options. Most travellers head straight to <strong>Corfu Town port</strong> — it's familiar, well-signposted and served by frequent crossings. But there's a second port that most guidebooks ignore: <strong>Lefkimmi</strong>, in the south of Corfu.</p>

        <h2 style="font-family:var(--fontH);color:var(--navy);font-size:26px;margin:36px 0 14px;">Corfu Town port — the classic route</h2>
        <p>The Igoumenitsa→Corfu Town line takes around <strong>1 hour 30 minutes</strong>. It's operated by Kerkyra Lines and Ionian Seaways with around 22 crossings per day in summer. Prices for foot passengers typically run €10–15. It's the right choice if you're heading to <strong>Corfu Town, Paleokastritsa, Dassia or Sidari</strong> — the north and centre of the island.</p>

        <h2 style="font-family:var(--fontH);color:var(--navy);font-size:26px;margin:36px 0 14px;">Lefkimmi port — the hidden shortcut</h2>
        <p>The Igoumenitsa→Lefkimmi line with <strong>Lefkimmi Lines</strong> takes just <strong>50 minutes</strong> — nearly half the crossing time. Prices start from <strong>€7.30 per foot passenger</strong> with the Transport Equivalent (state subsidy). Car fares start from ~€30.</p>
        <p>Lefkimmi is just 9 nautical miles from Igoumenitsa — that's why it's faster and cheaper. The port is small and friendly, with no queues and easy boarding.</p>

        <h2 style="font-family:var(--fontH);color:var(--navy);font-size:26px;margin:36px 0 14px;">When to choose Lefkimmi</h2>
