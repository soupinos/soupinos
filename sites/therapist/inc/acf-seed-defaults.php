<?php
/**
 * Praxis Therapist — first-run seed για τα ACF repeaters.
 *
 * Τα repeaters δεν υποστηρίζουν 'default_value', οπότε προ-γεμίζουμε
 * το approved περιεχόμενο μέσω acf/load_value σε φρέσκια εγκατάσταση.
 *
 * Λογική κάθε seed:
 *   1. Αν το $value έχει ήδη γραμμές → ο admin έχει δικά του, άσε.
 *   2. Αν υπάρχει αποθηκευμένο meta (έστω άδειο) → ο admin έχει σώσει
 *      ηθελημένα, ΜΗΝ ξαναγράφεις.
 *   3. Αλλιώς (ποτέ σωσμένο) → επέστρεψε το approved seed.
 *
 * ΠΡΟΣΟΧΗ: τα seed arrays χρησιμοποιούν sub-field NAMES (όχι field keys).
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Κοινός έλεγχος: έχει ο admin σώσει αυτό το repeater;
 * Επιστρέφει true αν δεν πρέπει να γίνει seed (υπάρχει value ή σωσμένο meta).
 */
function px_seed_skip( $value, $post_id, $field ) {
	if ( ! empty( $value ) ) {
		return true;
	}
	if ( is_numeric( $post_id ) && metadata_exists( 'post', (int) $post_id, $field['name'] ) ) {
		return true;
	}
	return false;
}

/* ── HERO SUB LINES ── */
add_filter( 'acf/load_value/key=field_hero_sub_lines', 'px_seed_hero_sub', 10, 3 );
function px_seed_hero_sub( $value, $post_id, $field ) {
	if ( px_seed_skip( $value, $post_id, $field ) ) {
		return $value;
	}
	return [
		[ 'line' => 'Ψυχοθεραπεία χωρίς εύκολες υποσχέσεις.' ],
		[ 'line' => 'Χωρίς life coaching.' ],
		[ 'line' => 'Χωρίς έτοιμες συνταγές.' ],
		[ 'line' => 'Χωρίς συνθήματα αυτοβελτίωσης.' ],
	];
}

